import Foundation

/// Which model writes the generated text, in the words the user is shown.
///
/// Every place that names the model — the label over a generated answer, a
/// tooltip on a suggested name, the consent sheet for row data — reads it
/// from here, so none of them can go on saying "Apple Intelligence" or
/// "nothing leaves this Mac" about text a custom endpoint wrote.
///
/// Foundation only: the settings are handed in as plain values, and the app
/// installs `current` at launch (`IntelligenceBackends.followSettings()`).
enum IntelligenceSource: Equatable {
    /// Apple's on-device model.
    case apple
    /// A custom endpoint. `host` is where a prompt goes; `onThisMac` says
    /// whether that is this machine.
    case endpoint(model: String, host: String, onThisMac: Bool)

    /// The source for the settings as they stand. Until the app installs
    /// its own, the on-device model: it is the only one a build without the
    /// settings can reach.
    static var current: () -> IntelligenceSource = { .apple }

    /// The source for a provider choice and an endpoint's address and model.
    /// An address that cannot be read still names the endpoint: the user
    /// chose it, and nothing may be labelled as Apple's that is not.
    init(usesEndpoint: Bool, address: String, model: String) {
        guard usesEndpoint else {
            self = .apple
            return
        }
        let name = model.trimmingCharacters(in: .whitespacesAndNewlines)
        switch IntelligenceEndpoint.baseURL(from: address) {
        case .success(let base):
            self = .endpoint(model: name, host: IntelligenceEndpoint.host(of: base),
                             onThisMac: IntelligenceEndpoint.isOnThisMac(base))
        case .failure:
            self = .endpoint(model: name, host: "", onThisMac: false)
        }
    }

    /// Whether a prompt leaves this Mac.
    var sendsOffThisMac: Bool {
        switch self {
        case .apple: return false
        case .endpoint(_, _, let onThisMac): return !onThisMac
        }
    }

    /// "Apple Intelligence", "llama3 on this Mac", "gpt-x at api.example.com".
    var name: String {
        switch self {
        case .apple:
            return String(localized: "Apple Intelligence")
        case .endpoint(let model, let host, let onThisMac):
            let model = model.isEmpty ? String(localized: "a custom model") : model
            if onThisMac { return String(localized: "\(model) on this Mac") }
            if host.isEmpty { return model }
            return String(localized: "\(model) at \(host)")
        }
    }

    /// The header over generated text.
    var generatedBy: String {
        String(localized: "Generated by \(name)")
    }

    /// The tooltip on a name field the model filled.
    var nameSuggestedBy: String {
        String(localized: "Name suggested by \(name)")
    }

    /// The model as the object of a sentence: "the on-device model",
    /// "llama3", "gpt-x at api.example.com".
    var modelPhrase: String {
        switch self {
        case .apple: return String(localized: "the on-device model")
        case .endpoint: return name
        }
    }

    /// Progress text while a request is out.
    var asking: String {
        String(localized: "Asking \(modelPhrase)\u{2026}")
    }

    /// The SF Symbol beside generated text. Apple's glyph is for Apple's
    /// model only; a caller falls back to `sparkles` where the SDK has no
    /// such symbol.
    var badgeSymbol: String {
        self == .apple ? "apple.intelligence" : "sparkles"
    }

    /// The consent sheet shown before a feature puts ROW values in a prompt.
    /// `what` names what will be read, as a noun phrase that starts a
    /// sentence.
    func rowDataConsent(what: String) -> (title: String, text: String) {
        switch self {
        case .apple:
            return (String(localized: "Send row data to the on-device model?"),
                    String(localized: "\(what) will be read by the model on this Mac. Nothing leaves this Mac."))
        case .endpoint(_, let host, let onThisMac):
            if onThisMac {
                return (String(localized: "Send row data to \(name)?"),
                        String(localized: "\(what) will be read by a model that runs on this Mac. Nothing leaves this Mac."))
            }
            let destination = host.isEmpty ? name : host
            return (String(localized: "Send row data to \(destination)?"),
                    String(localized: "\(what) will be sent to \(name). It leaves this Mac."))
        }
    }
}
